import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { GRADE_VOCABULARY } from '../data/gradeVocabulary.mjs'

const DATA_VERSION = '2.0.1'
const profileId = process.argv.slice(2).find((argument) => !argument.startsWith('--')) || 'grade-5'
const vocabulary = GRADE_VOCABULARY[profileId]

if (!vocabulary) throw new Error(`Unknown Stroke-order Slay profile: ${profileId}`)
if (!vocabulary.length) throw new Error(`No vocabulary has been configured for ${profileId}`)

const profileName = profileId.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase())
const exportName = `${profileName.replace(/^./, (character) => character.toUpperCase())}Rounds`
const outputFileName = `${profileName}Rounds.ts`

function sourceUrl(character) {
  return `https://cdn.jsdelivr.net/npm/hanzi-writer-data@${DATA_VERSION}/${encodeURIComponent(character)}.json`
}

function normalizeCoordinate(value) {
  return Math.round(Math.max(0, Math.min(100, value)) * 100) / 100
}

function normalizeMedian([x, y]) {
  return [normalizeCoordinate(x / 10.24), normalizeCoordinate(100 - y / 10.24)]
}

function pointToSegmentDistance(point, start, end) {
  const segmentX = end[0] - start[0]
  const segmentY = end[1] - start[1]
  const segmentLengthSquared = segmentX ** 2 + segmentY ** 2
  if (!segmentLengthSquared) return Math.hypot(point[0] - start[0], point[1] - start[1])
  const projection = Math.max(0, Math.min(1, (
    (point[0] - start[0]) * segmentX + (point[1] - start[1]) * segmentY
  ) / segmentLengthSquared))
  return Math.hypot(
    point[0] - (start[0] + projection * segmentX),
    point[1] - (start[1] + projection * segmentY),
  )
}

function simplifyMedian(points, tolerance = 1) {
  if (points.length <= 2) return points
  let farthestIndex = 0
  let farthestDistance = 0
  for (let index = 1; index < points.length - 1; index += 1) {
    const distance = pointToSegmentDistance(points[index], points[0], points[points.length - 1])
    if (distance > farthestDistance) {
      farthestDistance = distance
      farthestIndex = index
    }
  }
  if (farthestDistance <= tolerance) return [points[0], points[points.length - 1]]
  return [
    ...simplifyMedian(points.slice(0, farthestIndex + 1), tolerance).slice(0, -1),
    ...simplifyMedian(points.slice(farthestIndex), tolerance),
  ]
}

async function loadCharacter(character) {
  const url = sourceUrl(character)
  const response = await fetch(url)
  if (!response.ok) throw new Error(`Unable to load ${character}: ${response.status} ${response.statusText}`)
  const data = await response.json()
  if (!Array.isArray(data.medians) || !data.medians.length) throw new Error(`No stroke medians were returned for ${character}`)
  if (!data.medians.every((stroke) => Array.isArray(stroke) && stroke.length >= 2)) throw new Error(`Invalid stroke medians were returned for ${character}`)
  return { character, url, strokes: data.medians.map((stroke) => simplifyMedian(stroke.map(normalizeMedian))) }
}

const characters = [...new Set(vocabulary.flatMap(({ word }) => Array.from(word)))]
const characterData = new Map((await Promise.all(characters.map(loadCharacter))).map((data) => [data.character, data]))

const rounds = vocabulary.flatMap(({ lessonId, word, pinyin, meaning }, wordIndex) => Array.from(word).map((character, characterIndex) => {
  const data = characterData.get(character)
  return {
    id: `${profileId}-word-${wordIndex + 1}-character-${characterIndex + 1}`,
    targetId: `${profileId}-${character.codePointAt(0).toString(16)}`,
    targetText: character,
    audioText: word,
    meaning,
    lessonId,
    word,
    pinyin,
    wordCharacterIndex: characterIndex,
    wordCharacterCount: Array.from(word).length,
    strokes: data.strokes,
  }
}))

const sourceHeader = characters.map((character) => `// ${character}: ${characterData.get(character).url}`).join('\n')
const output = `// Generated by tools/importHanziWriterData.mjs. Do not hand-edit stroke coordinates.\n` +
  `// Hanzi Writer Data ${DATA_VERSION} sources:\n${sourceHeader}\n` +
  `import type { StrokeOrderGameRound } from '../runtime/contracts'\n\n` +
  `export const ${exportName} = ${JSON.stringify(rounds, null, 2)} as const satisfies readonly StrokeOrderGameRound[]\n`

if (process.argv.includes('--write')) {
  const destination = new URL(`../data/${outputFileName}`, import.meta.url)
  await writeFile(destination, output)
  process.stdout.write(`Wrote ${rounds.length} character rounds to ${fileURLToPath(destination)}\n`)
} else {
  process.stdout.write(output)
}
